/**
 * 역명 및 지리적 좌표를 바탕으로 최적의 행정구역(자치구/도시)을 판별
 */
export function resolveDistrict(stationName: string, coords?: [number, number]): string {
  const clean = stationName.replace(/역$/, '').trim()
  
  // 1. 역명 키워드 매칭
  for (const [key, dist] of Object.entries(STATION_DONG_MAP)) {
    if (clean.includes(key)) {
      return dist
    }
  }

  // 2. 좌표 기반 최근접 자치구 중심점 검색
  if (coords && coords.length === 2) {
    let minDist = Infinity
    let bestDistrict = '강남구'
    const [lng, lat] = coords
    for (const [dist, center] of Object.entries(DISTRICT_CENTERS)) {
      const d = Math.pow(lng - center[0], 2) + Math.pow(lat - center[1], 2)
      if (d < minDist) {
        minDist = d
        bestDistrict = dist
      }
    }
    return bestDistrict
  }

  return '강남구'
}
